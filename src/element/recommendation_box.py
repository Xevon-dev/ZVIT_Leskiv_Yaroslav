import flet as ft


def get_recommendation(wind, precip, pressure, temp, cloud, humidity, chance_of_rain, is_day, hour_idx):
    lines = []

    # --- Визначення часу доби ---
    if hour_idx < 6:
        time_label = "ніч"
    elif hour_idx < 10:
        time_label = "ранок"
    elif hour_idx < 16:
        time_label = "день"
    elif hour_idx < 21:
        time_label = "вечір"
    else:
        time_label = "ніч"


    if time_label == "ранок":
        lines.append("🌅 Ранок (06:00–10:00) — найкращий час для риболовлі. Риба активно годується після нічного спокою, тримається біля поверхні та на мілководді.")
    elif time_label == "день":
        if temp > 20:
            lines.append("☀️ День + спека — риба пішла на глибину і в тінь. Якщо вранці кльов був поганий — вдень буде ще гірше. Краще зробити паузу до вечора.")
        else:
            lines.append("🌤️ День — активність риби знижена порівняно з ранком. Якщо вранці кльов був слабким через погану погоду, вдень покращення малоймовірне.")
    elif time_label == "вечір":
        if temp > 20:
            lines.append("🌇 Вечір — другий найкращий час. Риба повертається з глибини на мілководдя годуватись. Якщо вдень не клювало через спеку — ввечері шанси значно кращі.")
        else:
            lines.append("🌆 Вечір (16:00–21:00) — хороший час для риболовлі, риба активізується після денного затишшя.")
    else:
        lines.append("🌙 Ніч — активні нічні хижаки: судак, сом, вугор. Мирна риба майже не клює. Потрібне спеціальне спорядження.")

    # --- Температура повітря (корелює з температурою води) ---
    if temp < 3:
        lines.append("🌡️ Дуже холодно (нижче 3°C) — риба практично не клює, обмін речовин мінімальний. Варто ловити лише на великих глибинах де вода тепліша.")
    elif temp < 8:
        lines.append("🌡️ Холодно (3–8°C) — кльов слабкий і непостійний. Активні лише окунь і щука. Використовуй повільніші проводки та менші приманки.")
    elif temp < 12:
        lines.append("🌡️ Прохолодно (8–12°C) — риба помірно активна. Починає годуватись активніше, особливо весною коли температура росте.")
    elif temp <= 22:
        lines.append("🌡️ Комфортна температура (12–22°C) — ідеальні умови. Більшість прісноводних риб максимально активна, добрий кльов протягом усього дня.")
    elif temp <= 27:
        lines.append("🌡️ Тепло (22–27°C) — активність зміщується на ранок і вечір. Вдень риба тримається глибини і тіні берегів.")
    else:
        lines.append("🌡️ Спека (вище 27°C) — риба майже не клює вдень. Вода перегрівається, кисень знижується. Лише ранній ранок або ніч.")

    # --- Вітер ---
    if wind > 35:
        lines.append("💨 Шторм (35+ км/год) — рибалка небезпечна і безглузда. Риба залягає на дно.")
    elif wind > 25:
        lines.append("💨 Сильний вітер (25–35 км/год) — складно закинути, хвилі каламутять воду. Спробуй ловити із захищеного берега або в затоці.")
    elif wind > 15:
        lines.append("💨 Помірний вітер (15–25 км/год) — навітряний берег краще: хвилі приносять корм і збагачують воду киснем. Риба активніша біля поверхні.")
    elif wind > 5:
        lines.append("💨 Легкий вітер (5–15 км/год) — сприятливі умови. Легке хвилювання маскує рибалку і покращує насичення води киснем.")
    else:
        lines.append("💨 Штиль — вода прозора і спокійна. Риба обережніша, бачить рибалку. Потрібна тонша снасть і тихіша поведінка.")

    # --- Опади з урахуванням шансу дощу ---
    if precip > 10:
        lines.append("⛈️ Сильна злива — кльов відсутній, вода каламутна. Краще повернутись додому.")
    elif precip > 3:
        lines.append("🌧️ Помірний дощ — кльов погіршується, але безпосередньо перед дощем зазвичай був сплеск активності.")
    elif precip > 0:
        lines.append("🌦️ Невеликий дощ — дощова поверхня маскує рибалку. Часто дає добрий кльов, особливо на поверхневі приманки.")
    else:
        if chance_of_rain >= 70:
            lines.append("🌂 Дощу немає, але висока ймовірність — риба відчуває зміну тиску перед дощем і активно годується. Зараз може бути відмінний кльов!")
        elif chance_of_rain >= 40:
            lines.append("🌤️ Можливий дощ — погода нестабільна. Кльов непередбачуваний, може бути як активним так і пасивним.")
        else:
            lines.append("☀️ Ясно без опадів — стабільна погода сприятлива для риболовлі, особливо якщо так було вже кілька днів.")

    # --- Хмарність ---
    if cloud >= 85:
        lines.append("☁️ Суцільна хмарність — риба менше боїться хижаків з повітря, піднімається до поверхні. Добрий кльов на поверхневі приманки.")
    elif cloud >= 50:
        lines.append("⛅ Мінлива хмарність — оптимальні умови. Хмари дають тінь і знижують освітленість, риба активніша і менш обережна.")
    elif cloud >= 20:
        lines.append("🌤️ Переважно ясно — риба обережніша на мілководді. Ловити краще на глибині або в тіні прибережних дерев.")
    else:
        lines.append("☀️ Повністю ясне небо — яскраве сонце насторожує рибу. Риба йде на глибину, потрібні важчі приманки і повільна проводка.")

    # --- Атмосферний тиск ---
    if 752 <= pressure <= 758:
        lines.append("🔵 Тиск ідеальний (752–758 мм) — стабільний нормальний тиск, найкращі умови для кльову. Риба активна на всіх горизонтах.")
    elif 748 <= pressure < 752 or 758 < pressure <= 763:
        lines.append("🔵 Тиск близький до норми — невеликі відхилення, риба помірно активна. Кльов є, але не пік.")
    elif pressure < 748:
        lines.append("🔵 Низький тиск (нижче 748 мм) — риба дезорієнтована, опускається глибше. Кльов слабкий. Щука і окунь ще можуть клювати.")
    elif pressure > 763:
        lines.append("🔵 Високий тиск (вище 763 мм) — риба стиснута у плавальному міхурі, пасивна. Тримається середніх горизонтів, кльов погіршується.")

    # --- Вологість ---
    if humidity >= 95:
        lines.append("💧 Критично висока вологість — туман або морось, видимість знижена. Риба часто активна в таких умовах, особливо вранці.")
    elif humidity >= 80:
        lines.append("💧 Висока вологість — комфортно для риби, насичення води киснем хороше.")
    elif humidity >= 60:
        lines.append("💧 Нормальна вологість — нейтральний вплив на кльов.")
    else:
        lines.append("💧 Низька вологість — сухе повітря, зазвичай супроводжується стабільним тиском. Сприятливо для рибалки.")

    # --- Загальний висновок ---
    score = 0
    if time_label in ("ранок", "вечір"):
        score += 2
    if 12 <= temp <= 22:
        score += 2
    if wind <= 15:
        score += 1
    if precip == 0 and chance_of_rain < 40:
        score += 1
    if 50 <= cloud <= 85:
        score += 1
    if 748 <= pressure <= 763:
        score += 2

    if score >= 8:
        lines.append("✅ ЗАГАЛЬНА ОЦІНКА: Відмінні умови для риболовлі — йди сміливо!")
    elif score >= 6:
        lines.append("👍 ЗАГАЛЬНА ОЦІНКА: Хороші умови — варто спробувати.")
    elif score >= 4:
        lines.append("⚠️ ЗАГАЛЬНА ОЦІНКА: Середні умови — кльов можливий, але непостійний.")
    else:
        lines.append("❌ ЗАГАЛЬНА ОЦІНКА: Погані умови — краще перенести рибалку.")

    return "\n\n".join(lines)


