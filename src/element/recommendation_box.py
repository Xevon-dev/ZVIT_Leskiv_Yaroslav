def get_time_of_day(hour_idx):
    if hour_idx < 6:
        return "ніч"
    elif hour_idx < 10:

        return "ранок"
    elif hour_idx < 16:
        return "день"
    elif hour_idx < 21:
        return "вечір"
    else:
        return "ніч"


def get_recommendation(wind, precip, pressure, temp, cloud, humidity, chance_of_rain, is_day, hour_idx):
    time_of_day = get_time_of_day(hour_idx)

    score = 0
    if time_of_day in ("ранок", "вечір"):
        score += 2
    if 12 <= temp <= 22:
        score += 2
    if wind <= 15:
        score += 1
    if precip == 0 and chance_of_rain < 40:
        score += 1
    if 50 <= cloud <= 85:
        score += 1
    if 748 <= pressure <= 763:
        score += 2

    morning_was_bad = temp > 22 or pressure < 748 or pressure > 763 or wind > 25 or precip > 3

    if morning_was_bad and time_of_day in ("ранок", "вечір"):
        score -= 2

    conditions_good = score >= 6
    conditions_mid = 4 <= score < 6
    conditions_bad = score < 4

    result = []

    if time_of_day == "ніч":
        result.append(
            "🌙 Зараз ніч - час нічних хижаків. Судак, сом і вугор активно полюють, "
            "тому якщо ціль саме вони - момент підходящий. "
            "Мирна риба (карась, лящ, плітка) вночі майже не клює - на неї розраховувати не варто."
        )
    elif time_of_day == "ранок":
        if morning_was_bad:
            result.append(
                "🌅 Ранок - зазвичай найкращий час, але зараз умови несприятливі. "
                "Риба менш активна через поганий тиск або сильний вітер - "
                "очікуй слабкий кльов навіть у цей час доби."
            )
        else:
            result.append(
                "🌅 Ранок - найкращий час доби для риболовлі. "
                "Риба активно годується після нічного спокою, "
                "тримається біля поверхні та на мілководді."
            )
    elif time_of_day == "день":
        if morning_was_bad:
            result.append(
                "☀️ День, і умови зранку вже були несприятливі. "
                "Риба, яка не годувалась вранці через погоду, вдень активніше не стане - "
                "навпаки, з прогрівом вона йде ще глибше і в тінь. "
                "Кращий варіант - дочекатись вечора або перенести рибалку."
            )
        elif temp > 20:
            result.append(
                "☀️ День і тепла погода - риба відійшла на глибину і в тінь берегів. "
                "Активність нижча ніж вранці, але при стабільному тиску кльов ще можливий."
            )
        else:
            result.append(
                "🌤️ День - активність риби дещо нижча ніж вранці, "
                "але при прохолодній погоді кльов цілком можливий."
            )
    else:  # вечір
        if morning_was_bad and temp > 20:
            result.append(
                "🌇 Вечір - і хоча вдень умови були поганими через спеку, "
                "саме зараз риба повертається з глибини на мілководдя годуватись. "
                "Вечір після спекотного дня - один з найкращих моментів для кльову."
            )
        elif morning_was_bad:
            result.append(
                "🌆 Вечір. Умови вдень були несприятливі, але з похолоданням і зниженням "
                "освітленості риба може активізуватись. Спробувати варто."
            )
        else:
            result.append(
                "🌆 Вечір - хороший час для риболовлі, "
                "риба активізується після денного затишшя."
            )

    weather_notes = []

    if temp < 3:
        weather_notes.append("дуже низька температура майже повністю пригнічує активність риби")
    elif temp < 8:
        weather_notes.append("холодна погода сповільнює рибу - активні лише окунь та щука")
    elif temp < 12:
        weather_notes.append("прохолодно, риба помірно активна")
    elif temp <= 22:
        weather_notes.append("температура комфортна для більшості прісноводних риб")
    elif temp <= 27:
        weather_notes.append("через тепло риба тримається глибини і тіні берегів")
    else:
        weather_notes.append("спека - вода перегрівається, кисень знижується, риба майже не клює")

    if wind > 35:
        weather_notes.append("штормовий вітер робить рибалку небезпечною")
    elif wind > 25:
        weather_notes.append("сильний вітер ускладнює закид і каламутить воду")
    elif wind > 15:
        weather_notes.append("помірний вітер приносить корм до навітряного берега - там краще ловити")
    elif wind > 5:
        weather_notes.append("легкий вітер маскує рибалку і насичує воду киснем")
    else:
        weather_notes.append("повний штиль - вода прозора, риба обережна, потрібна тонша снасть")

    if precip > 10:
        weather_notes.append("сильна злива повністю пригнічує кльов")
    elif precip > 3:
        weather_notes.append("помірний дощ погіршує кльов")
    elif precip > 0:
        weather_notes.append("невеликий дощ маскує рибалку і часто активізує кльов на поверхневі приманки")
    elif chance_of_rain >= 70:
        weather_notes.append("дощу ще немає, але риба вже відчуває зміну тиску перед ним і активно годується")
    elif chance_of_rain >= 40:
        weather_notes.append("нестабільна погода перед можливим дощем - кльов непередбачуваний")

    if 752 <= pressure <= 758:
        weather_notes.append("тиск ідеальний і стабільний - риба активна на всіх горизонтах")
    elif 748 <= pressure < 752 or 758 < pressure <= 763:
        weather_notes.append("тиск близький до норми - незначний вплив на рибу")
    elif pressure < 748:
        weather_notes.append("низький тиск дезорієнтує рибу - вона опускається глибше, кльов слабкий")
    else:
        weather_notes.append("високий тиск стискає плавальний міхур - риба пасивна і тримається середніх горизонтів")

    if cloud >= 85:
        weather_notes.append("суцільна хмарність знижує освітленість - риба менше боїться хижаків з повітря")
    elif cloud >= 50:
        weather_notes.append("мінлива хмарність дає тінь і знижує обережність риби")
    elif cloud < 20 and time_of_day == "день":
        weather_notes.append("ясне небо і яскраве сонце насторожують рибу на мілководді")

    if weather_notes:
        result.append("Погодні умови: " + "; ".join(weather_notes) + ".")

    if time_of_day == "ніч":
        if conditions_bad:
            result.append(
                "❌ Іти не варто - несприятливий тиск або вітер пригнічують навіть нічних хижаків. "
                "Краще дочекатись ранку."
            )
        elif conditions_mid:
            result.append(
                "⚠️ Можна спробувати - умови середні, але нічні хижаки активні. "
                "Судак: великі воблери або твістери біля перепадів глибин. "
                "Сом: живець або жаба на донку. Мирну рибу залиш до ранку."
            )
        else:
            result.append(
                "✅ Варто йти - хороший момент для нічних хижаків. "
                "Судак: великі воблери або твістери біля перепадів глибин. "
                "Сом: живець або жаба на донку. Мирну рибу залиш до ранку."
            )

    elif time_of_day == "день" and morning_was_bad:
        result.append(
            "❌ Іти не варто - вдень після поганого ранку кльову практично не буде. "
            "Якщо вже на місці - лови на найглибших ділянках з тінню, "
            "живець або черв'як спрацюють краще ніж штучні приманки."
        )

    elif conditions_good:
        if temp > 20 and time_of_day == "день":
            result.append(
                "✅ Варто йти - попри тепло, решта умов сприятлива. "
                "Лови на глибині або в тіні берегових дерев. "
                "Важчі приманки і повільна проводка дадуть кращий результат."
            )
        else:
            result.append(
                "✅ Варто йти - умови хороші, риба активна. "
                "Лови на звичні приманки для цього сезону."
            )

    elif conditions_mid:
        result.append(
            "⚠️ Можна спробувати - кльов можливий, але непостійний. "
            "Якщо 20–30 хвилин немає активності - зміни місце або глибину. "
            "Живець або натуральні насадки спрацюють краще ніж штучні приманки."
        )

    else:  # conditions_bad
        if wind > 25 or precip > 10:
            result.append(
                "❌ Іти не варто - погода робить рибалку безрезультатною. "
                "Якщо все ж виходиш - шукай захищені від вітру затоки."
            )
        elif pressure < 748 or pressure > 763:
            result.append(
                "❌ Іти не варто - аномальний тиск пригнічує рибу на кілька годин. "
                "Зазвичай потрібно 6–12 годин щоб тиск стабілізувався і риба відновила активність."
            )
        elif temp > 27:
            result.append(
                "❌ Іти не варто вдень - спека пригнічує рибу. "
                "Повернись ввечері: після заходу сонця активність різко зростає."
            )
        else:
            result.append(
                "❌ Іти не варто - сукупність факторів проти кльову. "
                "Якщо все ж виходиш, спробуй живця або натуральну насадку."
            )

    result.append(
        "ℹ️ Зверніть увагу: ці рекомендації базуються на загальних закономірностях поведінки риби. "
        "Кожна водойма має свої особливості - глибину, течію, рослинність і види риб - "
        "які можуть суттєво вплинути на кльов. "
        "Досвід на конкретному місці завжди точніший за будь-який прогноз."
    )

    return "\n\n".join(result)
